counts as (
  select s.id, s.slug, s.subject, s.name, s.grade_band::text as grade_band, s.ccss_grade,
         count(q.id) filter (where q.status = 'published') as published,
         count(q.id) filter (where q.status <> 'published') as not_published
  from public.skills s
  left join public.generated_questions q on q.skill_id = s.id
  where s.level = 'skill'
  group by s.id
)
