/**
 * Packs seeds/coverage/*.sql into numbered batch files that each fit in the
 * Supabase SQL editor (run with Bun, after build-coverage-seeds.ts):
 *
 *   bun run scripts/build-coverage-batches.ts
 *
 * Writes seeds/coverage-batches/NN_coverage.sql, numbered in run order:
 *   - New skills first (math, reading, writing; by grade), then top-ups of live
 *     skills, so nothing depends on a later batch.
 *   - Each batch stays under MAX_BYTES and starts with a guard that 0040 and
 *     0041 are applied.
 *   - Every seed inside keeps its own begin/commit and loads drafts only, so a
 *     batch is safe to re-run. If one seed fails, the ones before it in the
 *     batch stay loaded; fix and re-run the whole batch.
 *
 * content/content.test.ts fails if the batches are stale or a seed is missing.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const ROOT = join(here, '..')
export const SEEDS = join(ROOT, 'seeds', 'coverage')
export const BATCHES = join(ROOT, 'seeds', 'coverage-batches')

/** Supabase documents no SQL editor limit; 800 KB stays well inside what the browser editor handles. */
export const MAX_BYTES = 800_000

const GUARD = `do $guard$ begin
  if to_regclass('public.coverage_targets') is null then raise exception 'Run migration 0040 before the coverage batches.'; end if;
  if to_regclass('public.skill_standard_codes') is null then raise exception 'Run migration 0041 before the coverage batches.'; end if;
end $guard$;
`

const SUBJECT = { math: 0, read: 1, write: 2 } as Record<string, number>
const gradeOf = (f: string) => {
  const m = f.match(/^(?:math|read|write)-g(k|\d+)-/)
  return !m ? 99 : m[1] === 'k' ? 0 : Number(m[1])
}

/** Run order: new skills by subject then grade, top-ups (files that extend a live skill) last. */
export function orderSeeds(files: { name: string; sql: string }[]) {
  const isTopUp = (s: string) => s.includes('-- TOP-UP:')
  return [...files].sort((a, b) =>
    Number(isTopUp(a.sql)) - Number(isTopUp(b.sql)) ||
    (SUBJECT[a.name.split('-')[0]] ?? 9) - (SUBJECT[b.name.split('-')[0]] ?? 9) ||
    gradeOf(a.name) - gradeOf(b.name) ||
    a.name.localeCompare(b.name),
  )
}

export function buildBatches(files: { name: string; sql: string }[], maxBytes = MAX_BYTES) {
  const ordered = orderSeeds(files)
  const groups: { name: string; sql: string }[][] = []
  let cur: { name: string; sql: string }[] = []
  let size = 0
  for (const f of ordered) {
    const n = Buffer.byteLength(f.sql)
    if (cur.length && size + n > maxBytes) {
      groups.push(cur)
      cur = []
      size = 0
    }
    cur.push(f)
    size += n
  }
  if (cur.length) groups.push(cur)
  const total = groups.length
  return groups.map((g, i) => {
    const num = String(i + 1).padStart(2, '0')
    const questions = g.reduce((n, f) => n + (f.sql.match(/insert into public\.generated_questions/g) ?? []).length, 0)
    const header = `-- ===========================================================================
-- coverage batch ${num} of ${total}: ${g.length} seed(s), ${questions} draft questions
-- GENERATED by scripts/build-coverage-batches.ts. Do not edit by hand.
--
-- Paste the whole file into the Supabase SQL editor for papiowjjoyhnbyhgtbxq
-- and run it. Run batches in number order, after migrations 0040 and 0041.
-- Safe to re-run: everything loads as DRAFT, a re-run updates only unreviewed
-- drafts, and nothing publishes or changes a status.
--
-- Contains: ${g.map((f) => f.name.replace(/\.sql$/, '')).join(', ')}
-- ===========================================================================

`
    return { file: `${num}_coverage.sql`, sql: header + GUARD + '\n' + g.map((f) => f.sql).join('\n') }
  })
}

export function readSeeds() {
  return readdirSync(SEEDS)
    .filter((f) => f.endsWith('.sql'))
    .map((name) => ({ name, sql: readFileSync(join(SEEDS, name), 'utf8') }))
}

if (import.meta.main) {
  const batches = buildBatches(readSeeds())
  rmSync(BATCHES, { recursive: true, force: true })
  mkdirSync(BATCHES, { recursive: true })
  for (const b of batches) writeFileSync(join(BATCHES, b.file), b.sql)
  const biggest = Math.max(...batches.map((b) => Buffer.byteLength(b.sql)))
  console.log(`Wrote ${batches.length} batch file(s) to seeds/coverage-batches (largest ${Math.round(biggest / 1000)} KB).`)
}
